export type TranslationKey = keyof typeof pairs;

export function translate(locale: Locale, key: string): string {
  const mapped = aliases[key] ?? key;

  const entry = pairs[mapped as TranslationKey] ?? fields[mapped];

  return entry ? entry[locale === "uk" ? 1 : 0] : key.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/[_-]/g, " ");
}

export const translationKeys = Object.keys(pairs);

export function formatDate(
  value: string | Date,
  locale: Locale,
  timezone = "UTC",
  options?: Intl.DateTimeFormatOptions,
) {
  return new Intl.DateTimeFormat(locale === "uk" ? "uk-UA" : "en-GB", {
    timeZone: timezone,
    dateStyle: "medium",
    ...options,
  }).format(new Date(value));
}

export function formatDecimal(value: string | number, locale: Locale) {
  const input = String(value);
  if (!/^-?\d+(?:\.\d+)?$/.test(input)) return input;
  const [whole, fraction] = input.split(".");
  const numeric = BigInt(whole);
  const negativeZero = numeric === BigInt(0) && whole.startsWith("-");
  const formatted = new Intl.NumberFormat(locale).format(negativeZero ? -0 : numeric);
  const decimal =
    new Intl.NumberFormat(locale).formatToParts(1.1).find((part) => part.type === "decimal")?.value ?? ".";
  return fraction ? `${formatted}${decimal}${fraction}` : formatted;
}
